CREATE TABLE `system_job_status` (
  `job_name` VARCHAR(64) NOT NULL COMMENT '任务唯一名称',
  `display_name` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '任务中文名称',
  `status` VARCHAR(20) NOT NULL DEFAULT 'idle' COMMENT '任务状态：idle 空闲，running 运行中，retrying 等待重试，success 成功，failed 最终失败',
  `last_started_at` DATETIME(6) NULL COMMENT '最近一次开始时间',
  `last_finished_at` DATETIME(6) NULL COMMENT '最近一次结束时间',
  `last_success_at` DATETIME(6) NULL COMMENT '最近一次成功时间',
  `next_retry_at` DATETIME(6) NULL COMMENT '下次自动重试时间',
  `last_duration_ms` BIGINT NOT NULL DEFAULT 0 COMMENT '最近一次执行周期耗时，单位毫秒',
  `last_processed_count` INT NOT NULL DEFAULT 0 COMMENT '最近一次处理数量',
  `last_success_count` INT NOT NULL DEFAULT 0 COMMENT '最近一次成功数量',
  `last_failed_count` INT NOT NULL DEFAULT 0 COMMENT '最近一次失败数量',
  `last_attempt_count` INT NOT NULL DEFAULT 0 COMMENT '最近一次执行周期尝试次数',
  `consecutive_failures` INT NOT NULL DEFAULT 0 COMMENT '连续失败周期数',
  `manual_retry_count` INT NOT NULL DEFAULT 0 COMMENT '人工重试次数',
  `last_error` TEXT NULL COMMENT '最近一次失败的脱敏错误摘要',
  `locked_by` VARCHAR(100) NULL COMMENT '当前执行租约持有者',
  `lock_expires_at` DATETIME(6) NULL COMMENT '执行租约过期时间',
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6) COMMENT '更新时间',
  PRIMARY KEY (`job_name`),
  KEY `idx_system_job_status_status` (`status`),
  KEY `idx_system_job_status_next_retry_at` (`next_retry_at`),
  KEY `idx_system_job_status_lock_expires_at` (`lock_expires_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='系统定时任务运行状态';
