CREATE TABLE IF NOT EXISTS after_sale (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    after_sale_no VARCHAR(64) NOT NULL COMMENT 'A-prefixed after-sale business number',
    request_id VARCHAR(64) NOT NULL COMMENT 'idempotency key from client',
    order_id BIGINT NOT NULL COMMENT 'associated order_id',
    member_id BIGINT NOT NULL COMMENT 'associated member_id',
    type TINYINT NOT NULL COMMENT '1: refund only, 2: return and refund',
    status TINYINT NOT NULL DEFAULT 10 COMMENT '10:pending_review, 20:waiting_buyer_return, 30:waiting_merchant_receive, 40:refunding, 50:completed, 60:rejected, 70:cancelled, 80:refund_failed',
    order_status_at_apply TINYINT NOT NULL COMMENT 'order status snapshot at application',
    reason VARCHAR(100) NOT NULL DEFAULT '' COMMENT 'after-sale reason',
    description VARCHAR(1000) NOT NULL DEFAULT '' COMMENT 'detailed description',
    proof_file_ids JSON NULL COMMENT 'json array of system_file ids',
    refund_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT 'refund amount in yuan',
    return_receiver VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'return receiver name',
    return_phone VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'return contact phone',
    return_address VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'return shipping address',
    buyer_return_company VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'express company used by buyer',
    buyer_return_no VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'tracking number provided by buyer',
    reject_reason VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'reason for rejection by admin',
    applied_at DATETIME(6) NOT NULL COMMENT 'application time',
    audited_at DATETIME(6) NULL DEFAULT NULL COMMENT 'audit time',
    buyer_returned_at DATETIME(6) NULL DEFAULT NULL COMMENT 'buyer return shipment time',
    merchant_received_at DATETIME(6) NULL DEFAULT NULL COMMENT 'merchant package receipt time',
    refund_started_at DATETIME(6) NULL DEFAULT NULL COMMENT 'refund start time',
    completed_at DATETIME(6) NULL DEFAULT NULL COMMENT 'completion time',
    cancelled_at DATETIME(6) NULL DEFAULT NULL COMMENT 'cancellation time',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    UNIQUE KEY uk_after_sale_no (after_sale_no),
    UNIQUE KEY uk_after_sale_member_request (member_id, request_id),
    KEY idx_after_sale_order_id (order_id),
    KEY idx_after_sale_member_status (member_id, status),
    KEY idx_after_sale_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS after_sale_item (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    after_sale_id BIGINT NOT NULL COMMENT 'associated after_sale_id',
    order_item_id BIGINT NOT NULL COMMENT 'associated order_item_id',
    product_id BIGINT NOT NULL COMMENT 'product_id snapshot',
    sku_id BIGINT NOT NULL COMMENT 'sku_id snapshot',
    quantity INT NOT NULL DEFAULT 1 COMMENT 'after-sale quantity',
    refund_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT 'refund amount for this item',
    product_name VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'product name snapshot',
    sku_text VARCHAR(255) NOT NULL DEFAULT '' COMMENT 'sku spec description snapshot',
    sku_code VARCHAR(64) NOT NULL DEFAULT '' COMMENT 'sku code snapshot',
    sku_image_url VARCHAR(1024) NOT NULL DEFAULT '' COMMENT 'sku image url snapshot',
    restock_quantity INT NOT NULL DEFAULT 0 COMMENT 'actual restocked quantity',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY idx_after_sale_item_after_sale_id (after_sale_id),
    KEY idx_after_sale_item_order_item_id (order_item_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS after_sale_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    after_sale_id BIGINT NOT NULL COMMENT 'associated after_sale_id',
    operator_type TINYINT NOT NULL COMMENT '1: member, 2: admin, 3: system',
    operator_id BIGINT NOT NULL DEFAULT 0 COMMENT 'operator user/member id',
    operator_name VARCHAR(100) NOT NULL DEFAULT '' COMMENT 'operator name snapshot',
    from_status TINYINT NOT NULL DEFAULT 0 COMMENT 'original status',
    to_status TINYINT NOT NULL DEFAULT 0 COMMENT 'new status',
    action VARCHAR(64) NOT NULL COMMENT 'action name',
    remark VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'action remark or notes',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY idx_after_sale_log_after_sale_id_id (after_sale_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS order_refund (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    refund_no VARCHAR(64) NOT NULL COMMENT 'R-prefixed refund business number',
    after_sale_id BIGINT NOT NULL COMMENT 'associated after_sale_id',
    order_id BIGINT NOT NULL COMMENT 'associated order_id',
    payment_id BIGINT NOT NULL DEFAULT 0 COMMENT 'associated payment_id',
    member_id BIGINT NOT NULL COMMENT 'associated member_id',
    refund_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00 COMMENT 'refund amount in yuan',
    status TINYINT NOT NULL DEFAULT 10 COMMENT '10:pending, 20:processing, 30:success, 40:failed',
    provider VARCHAR(32) NOT NULL DEFAULT 'mock' COMMENT 'refund provider: mock, wechat, etc.',
    provider_refund_no VARCHAR(128) NULL DEFAULT NULL COMMENT 'external provider refund transaction id',
    retry_count INT NOT NULL DEFAULT 0 COMMENT 'retry attempts count',
    last_error VARCHAR(500) NOT NULL DEFAULT '' COMMENT 'last error message from provider',
    requested_at DATETIME(6) NULL DEFAULT NULL COMMENT 'last refund attempt time',
    refunded_at DATETIME(6) NULL DEFAULT NULL COMMENT 'refund success time',
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    UNIQUE KEY uk_order_refund_refund_no (refund_no),
    UNIQUE KEY uk_order_refund_after_sale_id (after_sale_id),
    KEY idx_order_refund_order_id (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
